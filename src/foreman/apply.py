def _gate_installed() -> bool:
    """Is the hook that would honour a `block` actually wired into the harness?

    Declaring blocking where nothing intercepts produces a rule that **reads as
    enforced and is not** — a guardrail in the index and a label in reality.
    That is the failure this design exists to remove, so it is worth a warning
    rather than a silent nothing.
    """
    try:
        from .agent_permissions import install

        return bool(install.wiring().get("hook_ok"))
    except Exception:
        return False


def _refusals(bundles: list[Bundle]) -> list[str]:
    """Declarations this build cannot honour. Each one stops the run.

    The alternative is silently doing the nearest thing that works — a rule
    asking to be blocked becoming a line of prose — which is a rule that is
    weaker than it says and nobody finding out.
    """
    out = []
    for bundle in bundles:
        for doc in bundle.docs:
            if doc.on_violation not in SUPPORTED_ON_VIOLATION:
                out.append(
                    f"{bundle.bundle_id} {doc.doc_id}: on_violation "
                    f"'{doc.on_violation}' is not implemented"
                )
    return out


def _notices(bundles: list[Bundle], project_root: Path) -> list[str]:
    """Things worth saying that are not worth stopping for."""
    out = []
    for bundle in bundles:
        for doc in bundle.docs:
            # `preload` is read only so it can be reported. Honouring it would
            # let a half-migrated bundle behave correctly and stall there
            # forever, which is the one outcome a migration cannot survive.
            if doc.legacy_preload:
                out.append(
                    f"{bundle.bundle_id} {doc.doc_id}: still declares "
                    f"preload — say what surfaces it with matches, or nothing"
                )
            # A glob matching nothing never fires, and silence is
            # indistinguishable from a rule that has simply not come up. Saying
            # so is the difference between *does not apply* and *will never be
            # seen*.
            for trigger in doc.matches:
                kind, _, value = trigger.partition(":")
                if kind != "path" or not value:
                    continue
                try:
                    if next(project_root.glob(value), None) is None:
                        out.append(
                            f"{bundle.bundle_id} {doc.doc_id}: nothing in this "
                            f"project matches '{value}' — the rule can never fire"
                        )
                except (ValueError, OSError):
                    continue
    return out


def _explain(bundles: list[Bundle]) -> None:
    """The derivation, per Document, with its input beside its outcome.

    **The class names live here and nowhere else that matters.** `always-on`,
    `advertised` and `on-demand` are not vocabulary an author has to learn
    before writing anything — they are a derived column, printed next to what
    produced it, so the rule is visible rather than memorised. A lookup table
    nobody has to hold in their head is a different thing from a glossary.
    """
    docs = sorted((d for b in bundles for d in b.docs),
                  key=lambda d: (d.bundle, d.doc_id))
    if not docs:
        return
    width = min(max((len(d.doc_id) for d in docs), default=0), 44)
    print()
    print(f"  {'document':<{width}}  {'matches':<26}  derives to")
    print(f"  {'-' * width}  {'-' * 26}  {'-' * 10}")
    for doc in docs:
        kinds = dict.fromkeys(m.partition(":")[0] for m in doc.matches)
        shown = ", ".join(kinds)
        print(f"  {doc.doc_id[:width]:<{width}}  {(shown or '—')[:26]:<26}  {doc.klass}")
    print()
    print("  A Document that matches nothing is not lost — its name and line are")
    print("  in the index above. Only its body waits to be asked for.")


def run(project_root: Path, check: bool, explain: bool = False) -> int:
    bundles = discover(project_root)

    # **An empty project is a state, not an error.** It used to exit 2, which
    # made the one case that has to be correct the one case never exercised:
    # a repository that has adopted nothing still needs an adapter, and a
    # repository whose last bundle just left still needs its rings swept. Both
    # go through here, so both are wrong if this refuses.

    refused = _refusals(bundles)
    if refused:
        print("cannot project — declarations this build cannot honour:", file=sys.stderr)
        for line in refused:
            print(f"  {line}", file=sys.stderr)
        return 2

    planned: dict[Path, str] = {}
    chosen, collided = _names(bundles)
    skills = project_root / ".claude" / "skills"
    for name, doc in chosen.items():
        bundle = next(b for b in bundles if b.bundle_id == doc.bundle)
        planned[skills / name / "SKILL.md"] = _skill(doc, bundle, project_root)
    for name, body in _navigation(bundles).items():
        planned[skills / name / "SKILL.md"] = body

    routing = adoption.bundles_dir(project_root) / "routing.toml"
    planned[routing] = _routing(bundles, project_root)

    planned[project_root / ENTRYPOINT] = _entrypoint(bundles, project_root)
    for bundle in bundles:
        planned[project_root / ring_path(bundle.bundle_id)] = _bundle_ring(
            bundle, project_root)

    claude = project_root / "CLAUDE.md"
    current = claude.read_text(encoding="utf-8") if claude.is_file() else ""
    planned[claude] = _splice(current, _adapter(bundles, project_root))

    kept = set(chosen) | set(NAVIGATION)
    stale = [p for p in _generated(skills).values() if p.name not in kept]

    # A ring for a bundle that left is worse than a missing one: it names
    # documents that are no longer on disk, and nothing about reading it says
    # so. Swept by the same rule as an orphaned skill.
    rings_root = project_root / ".luma" / "bundles" / "rings"
    orphan_rings = [
        r for r in sorted(rings_root.rglob("*.md"))
        if (project_root / ring_path(
            r.relative_to(rings_root).with_suffix("").as_posix())) not in planned
    ] if rings_root.is_dir() else []
    changed = [
        path
        for path, content in planned.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]

    if check:
        for path in sorted(changed):
            print(f"stale: {path.relative_to(project_root).as_posix()}")
        for path in sorted(stale) + orphan_rings:
            print(f"orphan: {path.relative_to(project_root).as_posix()}")
        if changed or stale or orphan_rings:
            print("\nrun `luma-foreman apply`")
            return 1
        print("up to date")
        return 0

    for path, content in planned.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for path in stale:
        shutil.rmtree(path)
    for path in orphan_rings:
        path.unlink()
        # An empty namespace directory left behind is a question a reader has to
        # answer. Walk up while each parent is empty and still inside rings/.
        parent = path.parent
        while parent != rings_root and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent

    workflows = sum(len(b.of_type("workflow")) for b in bundles)
    counts = {k: sum(len(b.of_class(k)) for b in bundles)
              for k in ("always-on", "advertised", "on-demand")}
    print(f"{len(bundles)} bundle(s) written out")
    print(f"  skills     {workflows} workflow(s) + {len(NAVIGATION)} navigation "
          f"-> .claude/skills/")
    print(f"  rings      1 project + {len(bundles)} bundle(s) -> .luma/bundles/")
    print(f"  always-on  {counts['always-on']} read when their own bundle's ring opens")
    print(f"  advertised {counts['advertised']} named, opened when they match")
    print(f"  on-demand  {counts['on-demand']} reachable, not announced")
    if explain:
        _explain(bundles)

    blocking = [d for b in bundles for d in b.docs if d.on_violation == "block"]
    if blocking and not _gate_installed():
        print()
        print(
            f"  WARNING  {len(blocking)} rule(s) declare blocking and nothing here "
            f"enforces them.\n"
            f"           The permission gate is not wired into this harness, so a "
            f"rule that\n"
            f"           reads as a guardrail is a label. Install it:\n"
            f"             luma-foreman agent-permissions install"
        )

    for line in _notices(bundles, project_root):
        print(f"  notice   {line}")
    if stale:
        print(f"  removed  {len(stale)} skill(s) for bundles no longer here")
    if orphan_rings:
        print(f"  removed  {len(orphan_rings)} ring(s) for bundles no longer here")
    if collided:
        print()
        print(
            "  note: these workflow names appear in more than one bundle and "
            "were\n        prefixed on both sides so neither is unreachable: "
            + ", ".join(collided)
        )
    if not changed and not stale and not orphan_rings:
        print("\n  (nothing changed)")
    else:
        print("\n  Commit the result, or gitignore .claude/ — it is generated either way.")
    return 0


def main(argv: list[str]) -> int:
    check = False
    explain = False
    target: Path | None = None
    rest = list(argv)
    while rest:
        arg = rest.pop(0)
        if arg in ("-h", "--help"):
            print(USAGE)
            return 0
        if arg == "--check":
            check = True
        elif arg == "--explain":
            explain = True
        elif arg == "--to":
            if not rest:
                print("luma-foreman apply: --to needs a directory", file=sys.stderr)
                return 2
            target = Path(rest.pop(0))
        else:
            print(f"luma-foreman apply: unknown option: {arg}", file=sys.stderr)
            return 2

    if target and not target.is_dir():
        print(f"luma-foreman apply: not a directory: {target}", file=sys.stderr)
        return 2
    project_root, _ = project.resolve(target or Path.cwd())
    return run(project_root, check, explain)
