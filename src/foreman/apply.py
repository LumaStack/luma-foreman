"""Projecting what a project adopted into what its harness actually reads.

**Adoption puts knowledge in the repository; nothing yet puts it in front of an
agent.** A bundle in `.luma/bundles/` is inert until something tells Claude Code
that it exists, and telling it is harness-specific work that the bundle must not
have to know about.

**Thin adapters, and thin is the whole design.** What gets written is a pointer
and a reason to follow it — never a copy of the document. A copy would be a
second source of truth that drifts from the first, and it would charge every
session for content that was supposed to load only when the work matched.

Two outputs, because a harness has two ways in:

| | |
| --- | --- |
| **skills** | one per `workflow`, so an agent can be *asked* to do the thing |
| **the entrypoint** | `.luma/bundles/entrypoint.md` — the project ring, naming what exists and what brings each part into play |
| **the adapter** | a block in `CLAUDE.md` that points at the entrypoint and carries nothing else |

**The entrypoint is the part that closes the gap.** Everything else assumes
somebody already knows the knowledge is there. Make existence cheap and content
expensive, so a consumer can always see what it is *not* loading.

**The adapter is separate from the ring on purpose.** A ring is the same thing
whatever is reading it, and a harness's file is not — so the ring is written
once and each harness gets a pointer. The adapter's one obligation beyond
pointing is to **not render what its harness already carries**: workflows reach
Claude Code as skills, whose names and descriptions it loads at startup, so the
ring does not list them a second time.

Everything written here is generated and disposable. The source is `.luma/`.
"""

from __future__ import annotations

import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

from . import adoption, lkf, project

USAGE = """Project adopted bundles into what this project's harness reads.

  luma-foreman apply             write the skills, the entrypoint and the adapter
  luma-foreman apply --check     report what would change, write nothing
  luma-foreman apply --explain   show what each Document derives to, and from what
  luma-foreman apply --to <dir>  a project other than this repository

Writes .claude/skills/<name>/SKILL.md for every workflow, .luma/bundles/entrypoint.md
naming everything adopted, and a managed block in CLAUDE.md pointing at it. All are
generated from .luma/ and are disposable — regenerate them rather than editing them.

Exit codes: 0 written (or up to date), 1 --check found staleness, 2 could not run."""

# Written into every generated file. It is what makes a later run able to tell
# what it owns from what somebody wrote by hand, which is what lets a skill for
# an un-adopted bundle actually leave.
MARK = "luma-foreman:generated"

# Only BEGIN_MARK is matched when locating an existing block. The rest of the
# line is prose and has been reworded once already — matching the whole string
# meant the rename orphaned the old block and appended a second one beside it.
BEGIN_MARK = "<!-- luma:begin"
BEGIN = f"{BEGIN_MARK} — generated by `luma-foreman apply`. Edits between these markers are lost. -->"
END = "<!-- luma:end -->"

# The project ring. It lives beside `adopted.toml` and `routing.toml` because
# all three are derived from what is in force and change exactly when it does —
# which is the lifecycle the tiers are cut by. The name is expected to move once
# there is something to look at; nothing depends on it but this line.
ENTRYPOINT = Path(".luma/bundles/entrypoint.md")

# `_types/` holds contracts, not reading material — a Type Definition is
# consulted when writing a document of that type, which is a job the workflow
# already sends you to. Listing them would double the index to say nothing.
SKIP = ("_types",)

SLUG = re.compile(r"[^a-z0-9-]+")

# Skill names foreman writes itself. Reserved, because they are the only route
# to a ring that does not depend on anything noticing — and a workflow quietly
# taking one would remove the floor the rest of the design stands on.
NAVIGATION = ("list-bundles", "load-bundle")

# What this build can actually do at the moment a rule is broken. The vocabulary
# is larger — `audit`, `warn`, `require_reason`, `require_approval` all mean
# something — and none of the rest is implemented. A declaration this cannot
# honour is refused rather than quietly downgraded to the nearest thing that
# works, because a rule that silently becomes weaker than it says is the exact
# failure the whole design exists to remove.
SUPPORTED_ON_VIOLATION = ("allow", "block")

# `README.md` is deliberately not an owner, whatever it contains. It carries
# universal permission semantics — everybody believes they may edit it freely —
# so a system that depends on its structure has a fuse in it, lit by the next
# person who tidies up.
NEVER_OWNS = ("README",)


def _owns_directory(path: Path) -> bool:
    """Is this the all-caps Document that its directory *is*?

    The casing is the signal rather than any particular word, so a workflow gets
    `WORKFLOW.md` and somebody's own type gets its own — nothing is centrally
    reserved, which the open type vocabulary requires.
    """
    stem = path.stem
    return stem.isupper() and stem not in NEVER_OWNS


@dataclass(frozen=True)
class Doc:
    """A Document inside a vendored bundle, as writing it out needs it."""

    bundle: str
    doc_id: str
    path: Path
    type: str
    title: str
    description: str
    on_violation: str
    matches: tuple[str, ...]
    legacy_preload: str = ""

    @property
    def slug(self) -> str:
        return SLUG.sub("-", self.doc_id.rsplit("/", 1)[-1].lower()).strip("-")

    @property
    def klass(self) -> str:
        """Where this lands: always-on, advertised, or on-demand.

        Derived, never declared — but **the expensive outcome is asked for
        rather than fallen into**. `matches: always` is the only route to
        always-on, so a Document cannot acquire a permanent seat in every
        session because somebody forgot a field.

        **The type no longer decides anything here**, and that is a
        simplification rather than an omission. It used to break the tie for a
        Document with no trigger — policy meant loaded-always, anything else
        meant findable. With the default reversed there is no tie: nothing
        surfaces a Document that says nothing surfaces it, whatever its type.

        **An unknown keyword lands here as on-demand**, which is the safe
        direction. `inspect` names it; the alternative is a typo buying a
        permanent seat in everybody's context.
        """
        if self.matches == ("always",):
            return "always-on"
        return "advertised" if self.matches else "on-demand"


@dataclass(frozen=True)
class Bundle:
    """A vendored bundle and the Documents worth projecting."""

    bundle_id: str
    root: Path
    version: str
    description: str
    docs: tuple[Doc, ...]
    entrypoint: str = ""

    def of_type(self, kind: str) -> list[Doc]:
        return [d for d in self.docs if d.type == kind]

    def of_class(self, klass: str) -> list[Doc]:
        return [d for d in self.docs if d.klass == klass]

    def always_on(self) -> list[Doc]:
        """Documents whose bodies have to be present before work starts."""
        return self.of_class("always-on")


def _text(keys: dict[str, str], name: str) -> str:
    return lkf.unquote(keys.get(name, "")).strip()


def discover(project_root: Path) -> list[Bundle]:
    """Every bundle in `.luma/bundles/`, adopted or written here.

    Both are written out. What a project wrote for itself is as much a part of how
    it works as what it took from a catalog, and an agent has no reason to care
    which is which — that distinction matters to drift checking, not to loading.
    """
    root = adoption.bundles_dir(project_root)
    if not root.is_dir():
        return []

    out: list[Bundle] = []
    for bundle_id, home in adoption.discover(project_root).items():
        manifest = home / "BUNDLE.md"
        keys = lkf.read(manifest) or {}

        # A directory that *is* a Document owns everything beneath it. Its
        # subordinates — a tutorial's steps, a template beside the workflow that
        # copies it — are reachable only through the owner and never announced
        # separately. That is the whole of subordination: no field, no
        # declaration, just where a file sits.
        owned: dict[Path, Path] = {}
        for path in sorted(home.rglob("*.md")):
            # The bundle's own manifest owns the bundle directory by exactly
            # this rule — and must not hide it. A bundle's members are its
            # content, which is the thing being written out; subordination
            # applies *within* a bundle, never at its root.
            if path.parent == home:
                continue
            if _owns_directory(path):
                owned[path.parent] = path

        def owner_of(path: Path) -> Path | None:
            for parent in path.parents:
                if parent in owned and owned[parent] != path:
                    return owned[parent]
                if parent == home:
                    break
            return None

        docs: list[Doc] = []
        for path in sorted(home.rglob("*.md")):
            rel = path.relative_to(home)
            if rel.parts[0] in SKIP or rel.as_posix() == "BUNDLE.md":
                continue
            if owner_of(path) is not None:
                continue  # subordinate: it arrives with its owner or not at all
            front = lkf.read(path)
            if front is None or "type" not in front:
                continue  # an Asset — a template, an example. Not addressable.

            # The directory is the identity. `WORKFLOW.md` is a local detail
            # nothing references, visible only to somebody already standing in
            # the directory — so the ID, the skill name and every link shorten
            # to the directory that holds it.
            doc_id = rel.parent.as_posix() if _owns_directory(path) else rel.as_posix()[:-3]

            docs.append(
                Doc(
                    bundle=bundle_id,
                    doc_id=doc_id,
                    path=path,
                    type=_text(front, "type"),
                    title=_text(front, "title"),
                    description=_text(front, "description"),
                    on_violation=_text(front, "on_violation") or "allow",
                    matches=lkf.matches(path),
                    legacy_preload=_text(front, "preload"),
                )
            )

        out.append(
            Bundle(
                bundle_id=bundle_id,
                root=home,
                version=_text(keys, "version"),
                description=_text(keys, "description"),
                docs=tuple(docs),
                # Both spellings while the rename finishes. A bundle that has
                # not been republished still has an answer to *where do I
                # start*, and reading only the new key would discard it.
                entrypoint=_text(keys, "entrypoint") or _text(keys, "entry_point"),
            )
        )
    return out


