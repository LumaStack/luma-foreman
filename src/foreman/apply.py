def _skill(doc: Doc, bundle: Bundle, project_root: Path) -> str:
    """One adapter: harness frontmatter, and where the real document is."""
    source = doc.path.relative_to(project_root).as_posix()
    lines = [
        "---",
        f"name: {doc.slug}",
        f"description: {doc.description}",
        "---",
        "",
        f"<!-- {MARK} from {bundle.bundle_id} {doc.doc_id}. "
        f"Regenerate with `luma-foreman apply`; edits are lost. -->",
        "",
        f"# {doc.title or doc.slug}",
        "",
        f"**Read `{source}` and follow it.** That file is the workflow. This is "
        f"the adapter that makes it reachable from here, and it deliberately "
        f"carries no copy of it — the copy would drift.",
    ]

    always_on = [d for d in bundle.always_on() if d.doc_id != doc.doc_id]
    if always_on:
        lines += ["", "Always-on context this workflow assumes:", ""]
        for d in always_on:
            rel = d.path.relative_to(project_root).as_posix()
            lines.append(f"- `{rel}` — {d.description or d.title or d.doc_id}")

    lines += [
        "",
        f"From the `{bundle.bundle_id}` bundle, vendored at "
        f"`{bundle.root.relative_to(project_root).as_posix()}/`. Do not edit "
        f"anything under there — an adopted bundle is a copy, and editing it is "
        f"drift.",
        "",
    ]
    return "\n".join(lines)


def _generated(skills: Path) -> dict[str, Path]:
    """Skill directories a previous run wrote, keyed by name."""
    if not skills.is_dir():
        return {}
    out = {}
    for path in sorted(skills.glob("*/SKILL.md")):
        try:
            if MARK in path.read_text(encoding="utf-8"):
                out[path.parent.name] = path.parent
        except (OSError, UnicodeDecodeError):
            continue
    return out


def _navigation(bundles: list[Bundle]) -> dict[str, str]:
    """The two skills that fire a ring on purpose rather than by noticing.

    **This is the floor.** Every other route depends on something matching — a
    trigger firing, a description catching a model's attention — and all of
    them degrade quietly when they do not. Asking by name cannot: it works when
    nothing notices, which is why it is built before any automatic firing and
    why its names are reserved.

    **Two skills, not one per bundle.** The cost is fixed however many bundles
    a project holds, so nothing here scales with adoption.
    """
    ring = ENTRYPOINT.as_posix()
    return {
        "list-bundles": f"""---
name: list-bundles
description: List the knowledge bundles this project has adopted, and what each one is for. Use when deciding which one to open, or when asked what this project knows.
---

<!-- {MARK} navigation. Regenerate with `luma-foreman apply`; edits are lost. -->

# What this project knows

Read `{ring}`. It names every adopted bundle, what each is for, and the path to
its ring.

**It is not copied here on purpose.** That file already arrives at the start of
a session, and rendering it a second time would charge twice for one list. What
this skill is for is the moment it has fallen out of context and you need it
back — so read the file, which is current, rather than a copy, which would not
be.

**This lists what is adopted, not what exists.** Bundles this project has not
taken are in whatever catalog it draws on, and nothing here can see them —
`luma-foreman catalog show <catalog>` is the command that can.
""",
        "load-bundle": f"""---
name: load-bundle
description: Open one adopted bundle and see what it holds — its rules, what fires each one, and anything that applies throughout it. Use when a bundle's line looks relevant, or when asked to load a bundle by name.
---

<!-- {MARK} navigation. Regenerate with `luma-foreman apply`; edits are lost. -->

# Open a bundle

Read `.luma/bundles/rings/<bundle-id>.md`.

**The bundle ID carries its namespace** — `lumastack/luma-catalog/git-secrets`,
never `git-secrets`. Guessing at one is the only way this fails, so take it from
`{ring}`, which lists every adopted bundle beside the path to its ring. Use
`/list-bundles` if you do not have a name at all.

**What you get.** Anything the bundle says applies throughout it, to read now;
then every rule it holds, with what fires each, and a line naming anything that
reaches you by another route. **Bodies are not included** — open the ones that
match the work, and not the rest.

**If the path does not exist**, the bundle is not adopted here. That is an
answer, not an error.
""",
    }


def _names(bundles: list[Bundle]) -> tuple[dict[str, Doc], list[str]]:
    """Assign a skill name to every workflow, and report what collided.

    A bare slug is what an agent matches against, so it is worth keeping. Two
    bundles may legitimately both publish `audit-bundle`, and the loser of a
    silent collision would simply never be reachable — so a collision renames
    **both** sides rather than letting first-seen win.
    """
    claims: dict[str, list[Doc]] = {}
    for bundle in bundles:
        for doc in bundle.of_type("workflow"):
            # **The two navigation skills are reserved.** They are the floor —
            # the one route that works when nothing notices — so a workflow
            # that happened to be called `load-bundle` must not be able to
            # replace one silently. It is renamed instead, exactly as it would
            # be against another workflow.
            slug = f"{SLUG.sub('-', doc.bundle.replace('/', '-').lower())}-{doc.slug}" \
                if doc.slug in NAVIGATION else doc.slug
            claims.setdefault(slug, []).append(doc)

    chosen: dict[str, Doc] = {}
    collided: list[str] = []
    for slug, docs in claims.items():
        if len(docs) == 1:
            chosen[slug] = docs[0]
            continue
        collided.append(slug)
        for doc in docs:
            prefix = SLUG.sub("-", doc.bundle.replace("/", "-").lower())
            chosen[f"{prefix}-{slug}"] = doc
    return chosen, sorted(collided)


