# the project ring, and the adapter that fires it


def _adapter(bundles: list[Bundle], project_root: Path) -> str:
    """The block in `CLAUDE.md`, which carries no knowledge of its own.

    **It points at the project ring and gets out of the way.** Everything it
    could say about what this project knows is said in the ring, and a fact
    stated in two places is a fact that will disagree with itself.

    The one thing it does carry is the `@` imports for always-on content, and
    that is a path question rather than a design one: `@` resolves against the
    file it appears in, so imports written here reach the repository root while
    the same lines written into the ring would not.
    """
    ring = (ENTRYPOINT.relative_to(project_root).as_posix()
            if ENTRYPOINT.is_absolute()
            else ENTRYPOINT.as_posix())
    lines = [
        BEGIN,
        "",
        "## Knowledge this project has adopted",
        "",
        f"**Read `{ring}` now.** It lists what this project knows, what each "
        "part is for, and what brings it into play. Nothing below repeats it.",
        "",
        f"@{ring}",
        "",
    ]

    # **Nothing from a bundle is hoisted here, and that is the change.** A
    # Document declaring `matches: always` used to be imported into every
    # session by every adopting project — so a rule holding throughout one
    # bundle was charged to work that never touched it. It is scoped to its own
    # ring now and arrives when the bundle does.
    #
    # What belongs here is whatever is `always` for the *project*, and nothing
    # can declare that yet: every Document lives in a bundle, so every `always`
    # is bundle-scoped by construction. Left empty deliberately rather than
    # filled by pretending a bundle's claim is the project's.

    lines += [
        "Generated by `luma-foreman apply`. Edits between the markers are lost; "
        "everything outside them is yours.",
        "",
        END,
    ]
    return "\n".join(lines)


def ring_path(bundle_id: str) -> Path:
    """Where a bundle's own ring is written.

    **Never inside the vendored copy.** ``adoption.checksum`` covers every file
    under a bundle's root, so a generated file placed there would report the
    bundle as edited — the drift check cannot tell our writing from somebody
    else's. Rings live beside the bundles rather than within them.

    ``rings/`` cannot be mistaken for a namespace: ``adoption.discover`` finds a
    bundle by its ``BUNDLE.md``, and nothing here has one.
    """
    return Path(".luma/bundles/rings") / f"{bundle_id}.md"


def _entrypoint(bundles: list[Bundle], project_root: Path) -> str:
    """`1-project`: what this repository knows, one line per bundle.

    **A ring's map names the members of the next ring in**, and the members of
    `2-bundle` are bundles — so this names bundles and stops. What is inside one
    is that bundle's own ring to answer, which is what keeps standing cost
    per-bundle instead of per-document.
    """
    lines = [
        "<!-- Generated by `luma-foreman apply`. Edits are lost. -->",
        "",
        "# What this project knows",
        "",
        "**One line per bundle, and nothing about what is inside one.** Open a "
        "bundle's ring when its line matches the work, and not before — the "
        "ring says what the bundle holds and what brings each part into play.",
        "",
        "Everything here is vendored under `.luma/bundles/` and is part of this "
        "repository. It is a copy: change it upstream and take it again, never "
        "in place.",
        "",
    ]

    # **Nothing adopted is a true thing to say, and the most useful one.** An
    # agent arriving cold learns that this project knows nothing yet and what
    # would change that — which beats an empty heading it has to interpret.
    if not bundles:
        return "\n".join(lines[:4] + [
            "**Nothing is adopted yet.** This project has taken no bundles, so "
            "there is nothing here to open.",
            "",
            "    luma-foreman catalog show <catalog>   what is available",
            "    luma-foreman get <bundle>             take one",
            "    luma-foreman apply                    rewrite this file",
            "",
        ])

    for bundle in bundles:
        ring = ring_path(bundle.bundle_id).as_posix()
        version = f" {bundle.version}" if bundle.version else ""
        lines.append(f"- **`{bundle.bundle_id}`**{version} — "
                     f"{bundle.description or 'no description'}")
        lines.append(f"  - ring: `{ring}`")
    lines.append("")

    lines += [
        "Every workflow in these bundles is installed as a skill and can be "
        "invoked by name. They are not named here or in a bundle's ring, "
        "because this harness already loads their names and descriptions.",
        "",
    ]
    return "\n".join(lines)


def _bundle_ring(bundle: Bundle, project_root: Path) -> str:
    """`2-bundle`: what one bundle holds, and what fires each part.

    **Paths, never `@`.** A ring is the same artifact whatever reads it, and
    `@` is one harness's import syntax — the adapter is where harness-specific
    delivery belongs. A reader that has opened this ring can open a path.

    **This is where a bundle's `always` lands, and that is the change.** It used
    to be imported into every session by every adopting project, so a rule that
    holds throughout one bundle was charged to work that never touched it.
    Scoped here, it arrives when the bundle does.
    """
    home = bundle.root.relative_to(project_root).as_posix()
    lines = [
        "<!-- Generated by `luma-foreman apply`. Edits are lost. -->",
        "",
        f"# `{bundle.bundle_id}`" + (f" {bundle.version}" if bundle.version else ""),
        "",
    ]
    if bundle.description:
        lines += [bundle.description, ""]

    # **The bundle's own answer to where to start, which nothing read until
    # now.** Twenty of the catalog's bundles declare `entrypoint` and it reached
    # no reader — a declared field nobody consumes, which is the same defect as
    # a rule nobody can see. It is a claim about reading order and nothing more,
    # so it earns a line at the top rather than a delivery of its own.
    entry = bundle.entrypoint
    if entry and any(d.doc_id == entry for d in bundle.docs):
        # Named without its description, because the list below carries that and
        # a ring is fifteen lines long — saying the same sentence twice in one is
        # the sort of thing an author does not notice and a reader cannot miss.
        lines += [f"**Start at `{entry}`.**", ""]

    always = bundle.of_class("always-on")
    if always:
        lines += [
            "**Read these now.** Each declares `matches: always`, so nothing "
            "gates when it governs — which means everything done with this "
            "bundle.",
            "",
        ]
        for doc in sorted(always, key=lambda d: d.doc_id):
            rel = doc.path.relative_to(project_root).as_posix()
            lines.append(f"- `{rel}` — {doc.description or doc.title}".rstrip(" —"))
        lines.append("")

    # **Anything that acts on a consumer gets its line, whatever its class.**
    # Existence is cheap and content is expensive. A policy that matches nothing
    # lands in on-demand, and a rule nobody can see governs nothing — listing
    # only the advertised ones would turn a cost saving into the silent absence
    # this whole design exists to end.
    #
    # Two deliberate exceptions. **Background** is left out on the format's own
    # reasoning (§10.7): it does not act, and it is reached *through* the things
    # that do. **Workflows** are left out because this harness already loads
    # every skill's name and description at startup, and an adapter must not
    # render what its harness already carries.
    shown = [d for d in bundle.docs
             if d.type != "workflow"
             and d.klass != "always-on"
             and (d.klass == "advertised"
                  or (d.klass == "on-demand" and d.type == "policy"))]
    # **Say what is not here, or the count is a lie.** A ring claims to say what a
    # bundle holds. `git-secrets` holds five Documents, this named two, and the
    # sentence explaining the other three lived only in the project ring — which
    # a reader arriving by `/load-bundle` never opened. Reachable and invisible
    # is the failure the whole design exists to end, and it was in the artifact
    # built to end it.
    workflows = bundle.of_type("workflow")
    if workflows:
        names = ", ".join(f"`{w.slug}`" for w in sorted(workflows, key=lambda d: d.slug))
        lines += [
            f"**{len(workflows)} workflow(s) here reach you as skills, not through "
            f"this ring** — invoke by name: {names}.",
            "",
        ]

    if shown:
        lines += [f"In `{home}/`:", ""]
        for doc in sorted(shown, key=lambda d: (d.type, d.doc_id)):
            note = doc.description or doc.title or ""
            when = ", ".join(doc.matches)
            teeth = " **[blocked]**" if doc.on_violation == "block" else ""
            lines.append(f"- `{doc.doc_id}` ({doc.type}){teeth} — {note}".rstrip(" —"))
            if when:
                lines.append(f"  - matches: {when}")
        lines.append("")
    elif not always and not workflows:
        lines += [f"Nothing here is named separately. In `{home}/`.", ""]

    return "\n".join(lines)


def _splice(existing: str, block: str) -> str:
    """Put *block* into *existing*, touching nothing outside the markers.

    A project's `CLAUDE.md` is mostly hand-written and belongs to whoever wrote
    it. Owning a delimited region of it is the most that can be taken without
    destroying somebody's work, and it is enough.
    """
    start = existing.find(BEGIN_MARK)
    end = existing.find(END)
    if start != -1 and end != -1 and end > start:
        return existing[:start] + block + existing[end + len(END) :]
    if not existing.strip():
        return block + "\n"
    return existing.rstrip("\n") + "\n\n" + block + "\n"


